"""Сверка каталога имён с настоящими сохранёнными выгрузками `.xprt`.

Зачем это отдельно от `test_catalog.py`. Там проверяется **устройство**
каталога и то, что он собран из движка, а `catalog_coverage` меряет, для
скольких классов имена проверяются. Ни та, ни другая проверка не отвечает на
вопрос «а весь ли набор имён у класса». Класс, у которого в каталоге осталось
одно имя, считается покрытым — и молча отвергает остальные.

Почему это опасно именно у нас. `SetBlockProp` не отвергает незнакомое имя:
ошибки нет, значение не меняется, модель считается по-другому. Поэтому
неполный набор имён — не «каталог чуть беднее», а отказ в законном параметре
(MCP-слой отвергает запись по каталогу) либо молчаливая потеря настройки.

Почему эталон — выгрузка, а не каталог. Сверять каталог с самим собой нечем:
расхождение обнаружено только сверкой с проектом, сделанным вне нас
(«Операция РАВНО»: `eps`/`checkerr` есть в реальном `EQ_6`, но не в каталоге;
«Интегратор с ограничением»: `minmaxsource`/`resettype` есть в проектах
поставки `Demo`, но не в каталоге).

Две проверки:

* `test_props_for_keeps_names_from_real_dumps` — по списку ниже, работают
  всегда, в том числе в CI, где ни поставки, ни выгрузок нет;
* `test_props_for_covers_saved_dumps` (маркер `distribution`) — сплошная
  сверка по `.xprt`, найденным на диске.
"""

