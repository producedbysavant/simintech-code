def test_props_for_keeps_names_from_real_dumps():
    """Каждое имя из эталона остаётся в `props_for` своего класса.

    Проверка падает, если имя удалить из каталога, — это и есть её смысл.
    """
    catalog = load_default_catalog()

    lost: dict[str, list[str]] = {}
    missing_classes = []
    for class_name, names in REFERENCE.items():
        if not catalog.has(class_name):
            missing_classes.append(class_name)
            continue
        absent = sorted(set(names) - set(catalog.props_for(class_name)))
        if absent:
            lost[class_name] = absent

    assert not missing_classes, (
        f"классы пропали из каталога: {missing_classes}")
    assert not lost, f"каталог потерял имена, снятые с реальных выгрузок: {lost}"


# ─── Сплошная сверка по выгрузкам на диске ────────────────────────

#: Где искать выгрузки. По умолчанию — поставка SimInTech64: в ней лежат
#: примеры из `doc/`. Эксплуатационные проекты живут вне поставки, поэтому их
#: каталоги добавляются переменной `SIMINTECH_XPRT_DIRS` (разделитель —
#: `os.pathsep`). Без переменной проверка идёт только по поставке.
DISTRIBUTION = os.environ.get("SIMINTECH_ROOT", "/mnt/c/SimInTech64")
EXTRA_DIRS = os.environ.get("SIMINTECH_XPRT_DIRS", "")


def _saved_dumps():
    """Пути всех `.xprt` на диске — поставка плюс `SIMINTECH_XPRT_DIRS`.

    Рабочие каталоги среды (`Temp`, `~`) пропускаются: в них пишут и наши
    прогоны, и сама среда, поэтому набор файлов там меняется от запуска к
    запуску, и проверка, опирающаяся на них, краснела бы и зеленела случайно.
    """
    roots = [DISTRIBUTION]
    roots.extend(part for part in EXTRA_DIRS.split(os.pathsep) if part)
    skip = {".git", "__pycache__", "Temp"}
    found = []
    for root in roots:
        if not os.path.isdir(root):
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in skip]
            for name in filenames:
                if name.lower().endswith(".xprt"):
                    found.append(os.path.join(dirpath, name))
    return sorted(found)


@pytest.mark.distribution
def test_props_for_covers_saved_dumps():
    """Имена из каждой найденной выгрузки есть в `props_for` своего класса.

    Сплошная проверка по файлам: класс, которым каталог не знает вовсе,
    пропускается — это предмет `catalog_coverage`, а не полноты набора. Но
    хотя бы один класс проверен быть обязан: иначе проверка «зелена» ровно
    потому, что не делала ничего.
    """
    dumps = _saved_dumps()
    if not dumps:
        pytest.skip(f"выгрузок нет: {DISTRIBUTION}")

    catalog = load_default_catalog()
    checked: set[str] = set()
    diverged: dict[str, dict[str, list[str]]] = {}

    for path in dumps:
        text = decode_xprt(pathlib.Path(path).read_bytes())
        for class_name, names in parse_xprt_block_props(text).items():
            if not names or not catalog.has(class_name):
                continue
            absent = sorted(set(names) - set(catalog.props_for(class_name)))
            checked.add(class_name)
            if absent:
                diverged.setdefault(class_name, {})[path] = absent

    assert checked, (
        f"ни одного класса не сверено, хотя выгрузок {len(dumps)}: "
        f"сверка ничего не проверила")
    assert not diverged, (
        f"каталог не знает имён, которые есть в реальных выгрузках: "
        f"{diverged}")
