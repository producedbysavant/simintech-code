"""Канон укладки (ТЗ 4.2): ширина канала и мощность разреза.

Живёт в библиотеке раскладки, а не в потребителе: формулу канала считают и
шаг слоёв (`LayeredPlacer`), и аудит читаемости (сверка фактического зазора
с каноном). Вторая копия формулы рано или поздно разошлась бы с первой.
"""

from __future__ import annotations

from typing import List, Tuple

# `as`-форма — явный реэкспорт: канон отдаёт эти константы наружу
# (`placer` импортирует WIRE_PITCH именно отсюда), а mypy strict без
# явного реэкспорта считает импорт приватным ([attr-defined]).
from ..constants import STUB as STUB, WIRE_PITCH as WIRE_PITCH

#: Допуск «связь выровнена»: Y конца у источника и Y конца у приёмника
#: совпадают (ТЗ 4.1). Полпикселя — координаты считаются целыми.
ALIGN_EPS = 0.5


def channel_width(cut: int) -> float:
    """Ширина канала между колонками (ТЗ 4.2).

    `cut` — мощность разреза между парой колонок. Даже при нуле связей канал
    не схлопывается: в нём остаётся место хотя бы под один трек.
    """
    return STUB + WIRE_PITCH * max(1, cut)


def cut_sizes(nets: "List[Tuple[int, int, bool]]", gaps: int) -> "List[int]":
    """Мощность разреза для каждого зазора между колонками (ТЗ 4.2).

    `nets` — по связи: (колонка источника, колонка приёмника, выровнена).
    Связь, выровненная в одну горизонталь, трека на разрезе не занимает и в
    мощность не входит. Для зазора `i` считаются связи с источником в колонке
    `<= i` и приёмником в колонке `>= i + 1`. Обратные связи (приёмник не
    правее источника) сюда не попадают: по ТЗ 4.3 им место в нижнем канале.
    """
    return [
        sum(1 for src, dst, aligned in nets
            if not aligned and src <= gap < dst)
        for gap in range(gaps)
    ]


def round_step(step: float) -> float:
    """Шаг колонки — ВВЕРХ до шага трека: округление не съедает канал (ТЗ 4.2).

    Канон даёт ширину канала, кратную `WIRE_PITCH`, но полуширины соседей могут
    быть нечётными (порт 260 → 130), и центр уезжает с разметки. Снап в MCP
    тогда двигал бы X и подрезал зазор на 2–4 px — аудит ловит это как overflow.
    Округление шага вверх сохраняет разметку и растит зазор, а не режет его.
    """
    return -(-step // WIRE_PITCH) * WIRE_PITCH
