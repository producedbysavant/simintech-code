"""Сборка и разбор пробных скриптов SimInTech — без COM.

Скриптовый мост устроен так: внешний клиент кладёт в проект скрипт страницы,
запускает расчёт и читает файл, который скрипт записал. Средств диагностики у
среды нет — измерено 2026-09-21 на SimInTech64: ошибка скрипта наружу не
сообщается ничем, а `SetPageScript` возвращает 1 и при синтаксически неверном
скрипте. Поэтому единственный различимый признак обрыва — отсутствие маркера
завершения, который скрипт пишет последней строкой.

Здесь лежит всё, что проверяется без COM: сборка текста скрипта, разбор
результата и разбор скриптовых записей выгрузки `.xprt`. COM-часть —
`simintech_api/core/script_bridge.py`.
"""

from __future__ import annotations

import random
import re
from typing import List, NamedTuple, Optional

from .exceptions import ScriptBridgeError, ScriptBridgeUnsafeStateError

#: Маркеры, между которыми скрипт пишет полезные строки. Отсутствие конечного
#: означает, что скрипт оборвался: ошибка времени выполнения молча прекращает
#: его выполнение, а среда об этом не сообщает.
BEGIN_MARKER = "SCRIPT_BRIDGE_BEGIN"
END_MARKER = "SCRIPT_BRIDGE_END"

#: Префикс метки цели. Метка — **доказательство**, что скриптовую запись
#: изменили мы, а не просто «единственная изменившаяся»: без неё запись чужой
#: страницы, изменившаяся сама по себе, была бы принята за нашу, и возврат
#: положил бы в текущую страницу чужой скрипт.
#: Пробела после `//` нет намеренно: контракт метки запрещает пробелы, потому
#: что выгрузка кодирует часть символов кодами `#NN`, и метка, зависящая от
#: того, кодируется ли пробел литерально, хрупка. Комментарий `//` пробела не
#: требует.
TARGET_TOKEN_PREFIX = "//SCRIPT_BRIDGE_TARGET_"

#: Длина случайной части метки в шестнадцатеричных знаках.
TARGET_TOKEN_HEX_DIGITS = 32

#: Префикс имени, под которым проба держит **свой** дескриптор результата.
BRIDGE_DESCRIPTOR_PREFIX = "br_result_"

#: Имя, которое видит тело пробы — и чужой код внутри него. Это приманка, а не
#: дескриптор моста: она связана с дескриптором первой же строкой тела, поэтому
#: тела, пишущие `writelnutf8(fid, ...)`, работают как раньше, а присваивание
#: `fid` чужой процедурой (вендорская `export_1layer_topology` делает именно
#: это, не объявляя имя) уводит приманку, а не дескриптор моста.
DECOY_DESCRIPTOR_NAME = "fid"

#: Процедура записи в дескриптор моста — путь, которого присваивание не
#: касается. Имя постоянное: тело должно уметь её позвать.
BRIDGE_WRITE_PROCEDURE = "br_writeln"


def new_target_token(rng: Optional[random.Random] = None) -> str:
    """Сгенерировать метку цели — комментарий языка, свой на каждый запуск.

    Метка состоит только из ASCII-знаков и не содержит кавычек, обратных
    кавычек, решётки, пробелов и переводов строк. Это не стилистика: решётка
    сделала бы метку неотличимой от кодов `#NN`, которыми выгрузка кодирует
    спецсимволы, а кавычка и перевод строки ломают разметку значения `<script>`.

    `rng` — источник случайности, по умолчанию `SystemRandom`. Параметр нужен
    тестам: воспроизводимость важнее удобства.
    """
    source = rng if rng is not None else random.SystemRandom()
    digits = "".join(source.choice("0123456789abcdef")
                     for _ in range(TARGET_TOKEN_HEX_DIGITS))
    return TARGET_TOKEN_PREFIX + digits


class ProbeResult(NamedTuple):
    """Разобранный результат пробы.

    `complete` — есть ли маркер завершения. `lines` — строки между маркерами;
    у оборванного результата это то, что успело записаться.
    """

    lines: List[str]
    complete: bool


def bridge_descriptor_name(token: str) -> str:
    """Имя дескриптора моста — из случайной части метки запуска.

    Имя **порождается** меткой, а не выбирается константой, и это не стилистика.
    Измерено 2026-09-24 на поставке: вложенная процедура видит и **изменяет**
    переменные охватывающего блока (вендорская процедура так и затирала `fid`
    моста), а тень имени во вложенном блоке язык запрещает — объявление
    отвергается как ошибка компиляции. Значит, отдельной области видимости для
    дескриптора у языка нет, и единственная доступная изоляция — недостижимость
    по имени: чужой текст не может ни назвать это имя, ни присвоить его.

    Метка случайна на каждый запуск и проверена на отсутствие в проекте
    (`token_present_in`), поэтому её случайная часть — подходящая основа имени.
    """
    return BRIDGE_DESCRIPTOR_PREFIX + token.rsplit("_", 1)[-1]


def build_probe_script(body: str, result_path: str, token: str) -> str:
    """Собрать скрипт страницы, который выполнит `body` и запишет результат.

    `body` — строки на встроенном языке, пишущие результат в уже открытый файл
    вызовами `writelnutf8(fid, ...)` или `br_writeln(...)`. Открытие файла,
    маркеры и закрытие берёт на себя эта функция, поэтому телу не нужно знать
    про маркеры.

    **Дескриптор моста телу по имени недоступен.** Мост держит его под именем,
    порождённым меткой запуска (`bridge_descriptor_name`), а `fid` — приманка,
    связанная с этим дескриптором первой же строкой тела. Тела, пишущие
    `writelnutf8(fid, ...)`, работают как раньше; но присваивание `fid` чужой
    процедурой уводит приманку, а дескриптор моста и его маркеры не трогает.

    Зачем так. Вендорская процедура `export_1layer_topology` присваивает
    `fid = createfile(...)`, не объявляя имя, и освобождает дескриптор в конце.
    Пока мост писал через то же имя, присваивание уводило **его** дескриптор:
    конечный маркер уходил в чужой уже освобождённый файл, проба обрывалась, а
    файл результата оставался с одним начальным маркером. Измерено на поставке:
    так ведёт себя и настоящая вендорская процедура, и её синтетический повтор.

    Тело, зовущее чужой код, пишет результат после такого вызова через
    `br_writeln`: приманка `fid` к тому моменту указывает на чужой (возможно,
    уже освобождённый) файл, и запись через неё обрывает скрипт.

    `token` — метка цели (`new_target_token`): по ней мост опознаёт в выгрузке
    ту скриптовую запись, которую изменил он сам, и по ней же строится имя
    дескриптора моста.

    Метка ставится **первой строкой**, до исполняемого тела: тогда она остаётся
    в скрипте, даже если тело не скомпилировалось, — а именно этот случай и
    надо уметь опознать, чтобы вернуть прежний скрипт.

    Тело идёт под `if firststep then`, а не в секцию `initialization`: на
    инициализации порты субмоделей могут быть ещё не установлены, и обход
    топологии даст неполную картину (сказано в демо поставки «Анализ
    топологии скриптами»).

    Путь переводится в **прямые** слэши. Разбирает ли встроенный язык `\\t` и
    `\\r` в строковом литерале как управляющие последовательности — **не
    измерено** (язык Паскалевый, где обратный слэш таковым не является, — но
    это довод, а не измерение). Если разбирает, `C:\\tmp\\result.txt` стал бы
    `C:<TAB>mp<CR>esult.txt`, `createfile` ушёл бы не туда, а отказ выглядел бы
    как обычный сбой скрипта: «нет ровно одной пары маркеров». Прямые слэши
    безопасны при **обоих** прочтениях: Windows их принимает, а экранировать в
    них нечего. Меняется только то, что попадает в литерал, — сам путь в
    остальном не трогается.
    """
    if '"' in result_path or "\n" in result_path or "\r" in result_path:
        raise ValueError(
            "путь результата не может содержать кавычку или перевод строки: "
            f"{result_path!r} — он подставляется в литерал встроенного языка")
    literal_path = result_path.replace("\\", "/")
    name = bridge_descriptor_name(token)
    indented = "".join(
        f"  {line}\n" for line in body.splitlines() if line.strip())
    return (
        f"{token}\n"
        "if firststep then begin\n"
        f"  var {name}: integer;\n"
        f"  var {DECOY_DESCRIPTOR_NAME}: integer;\n"
        f"  procedure {BRIDGE_WRITE_PROCEDURE}(s: string);\n"
        f"    writelnutf8({name}, s);\n"
        "  end;\n"
        f'  {name} = createfile("{literal_path}", -1);\n'
        f'  writelnutf8({name}, "{BEGIN_MARKER}");\n'
        f"  {DECOY_DESCRIPTOR_NAME} = {name};\n"
        f"{indented}"
        f'  writelnutf8({name}, "{END_MARKER}");\n'
        f"  freeobject({name});\n"
        "end;\n"
    )


def parse_probe_result(text: str) -> ProbeResult:
    """Разобрать файл результата.

    Полным считается результат **ровно с одной парой маркеров**, где конечный
    идёт после начального. «Ровно одна пара» — не придирка: если маркер
    встретился ещё и в данных, границу протокола провести нельзя, и результат
    обязан считаться неполным, а не угаданным. Раньше брался первый конечный
    маркер, поэтому строка данных, совпавшая с ним, объявляла оборванную пробу
    полной и молча отбрасывала хвост.

    У неполного результата `lines` **пуст**: частичные данные использовать
    нельзя, а держать их рядом с флагом — приглашение однажды ими
    воспользоваться.
    """
    lines = text.splitlines()
    begins = [i for i, line in enumerate(lines) if line == BEGIN_MARKER]
    ends = [i for i, line in enumerate(lines) if line == END_MARKER]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        return ProbeResult(lines=[], complete=False)
    return ProbeResult(lines=lines[begins[0] + 1:ends[0]], complete=True)


#: Значение в выгрузке `.xprt` — последовательность кусков в обратных кавычках
#: и кодов `#NN` между ними. Кодами пишется всё, что неудобно писать буквально:
#: `#13#10` — перевод строки, `#9` — табуляция, `#60` — `<`, `#62` — `>`.
#: Разбираем токенами, а не подстановкой отдельных кодов: проверено на
#: поставке — в 1181 непустом скрипте покрытие полное, остатка нет.
_TOKEN_RE = re.compile(r"`([^`]*)`|#(\d+)")


def decode_xprt_value(raw: str) -> str:
    """Раскодировать значение выгрузки: куски в кавычках плюс коды `#NN`.

    Коды раскодируются **любые**, а не только перевод строки и табуляция: в
    поставке встречаются `#60` и `#62` (`<` и `>`), и оператор сравнения в
    скрипте иначе вернулся бы на место нерабочим — молча, потому что среда об
    ошибке скрипта не сообщает.

    Обратная кавычка внутри скрипта приходит кодом `#96` и потому не путается
    с кавычками-обёртками.

    Код, из которого символа не выходит, — отказ, а не исключение из недр
    `chr()`: `leftover_of` такую запись считает покрытой, поэтому «покрыта» и
    «разбирается» — разные вещи, и разница обязана быть видна вызывающему.
    Таких кодов два вида:

    * вне диапазона Unicode (`#1114112` и больше) — `chr()` бросает `ValueError`
      прямо здесь;
    * одиночный суррогат (`#55296`…`#57343`) — `chr()` его принимает, но такого
      символа не существует в UTF-8, и падение случилось бы позже, сырым
      `UnicodeEncodeError` при записи скрипта обратно в проект.
    """
    parts = []
    for chunk, code in _TOKEN_RE.findall(raw):
        if code == "":
            parts.append(chunk)
            continue
        value = int(code)
        if value > 0x10FFFF:
            raise ScriptBridgeError(
                f"код #{code} в значении выгрузки вне диапазона Unicode: "
                "разобрать запись нечем, а подставить вместо символа нечто "
                "другое значило бы испортить скрипт молча.")
        if 0xD800 <= value <= 0xDFFF:
            raise ScriptBridgeError(
                f"код #{code} в значении выгрузки — одиночный суррогат: такого "
                "символа в UTF-8 не существует, и запись скрипта обратно в "
                "проект упала бы сырым UnicodeEncodeError уже вне иерархии "
                "ошибок моста.")
        parts.append(chr(value))
    return "".join(parts)


def leftover_of(raw: str) -> str:
    """Часть значения, не покрытая ни куском, ни кодом.

    Нужна проверкам: непустой остаток означает, что разбор теряет текст и
    вернул бы на место испорченный скрипт.
    """
    return _TOKEN_RE.sub("", raw)


#: Скрипт страницы в выгрузке — `<script>` **сразу за** `<name>` страницы.
#: Имя бывает пустым и без обратных кавычек (`<name></name>`) — измерено на
#: странице субмодели демо вендора, и прежний разбор, требовавший кавычек,
#: пропускал такую страницу. Кавычки вокруг значения необязательны: пустой
#: скрипт пишется как `<script></script>`.
#:
#: Почему «сразу за»: у объектов внутри страницы есть свои `<script>` — скрипты
#: свойств в `<data>`. Взять первый `<script>` внутри страницы значило бы
#: схватить чужой.
_PAGE_SCRIPT_RE = re.compile(
    r"<page>\s*<name>(?:`[^`]*`)?</name>\s*<script>(.*?)</script>", re.S)

#: Открывающий тег страницы — для сверки числа записей с числом страниц.
_PAGE_OPEN_RE = re.compile(r"<page>")


def parse_xprt_script_records(xprt_text: str) -> List[str]:
    """Снять скриптовые записи выгрузки — **сырыми**, в порядке следования.

    Сырыми, а не декодированными: снимки сравниваются как текст файла, и это
    тот же уровень, на котором измерено «`SetPageScript` меняет ровно одну
    запись». Кодировку разбирает **не эта функция**: вызывающий декодирует
    (`decode_xprt_value`) ровно ту запись, которую предстоит вернуть на место.

    Разбор проверяет себя: число разобранных записей обязано совпасть с числом
    страниц. Молча пропущенная страница сдвинула бы нумерацию, и возврат
    положил бы чужой скрипт — поэтому расхождение это отказ, а не «сколько
    получилось».
    """
    records = _PAGE_SCRIPT_RE.findall(xprt_text)
    pages = len(_PAGE_OPEN_RE.findall(xprt_text))
    if len(records) != pages:
        raise ScriptBridgeError(
            f"в выгрузке {pages} страниц, но скриптовых записей разобрано "
            f"{len(records)}: форма выгрузки не та, что измерена, и продолжать "
            "нельзя — сдвиг нумерации записей означал бы возврат чужого скрипта")
    return records


def token_present_in(records: List[str], token: str) -> bool:
    """Встречается ли метка хоть в одной скриптовой записи."""
    return any(token in record for record in records)


def find_changed_script_record(before: List[str], after: List[str],
                               token: str) -> int:
    """Номер скриптовой записи, которую изменила установка пробы.

    Условие цели — три части, и все обязательны:

    1. изменилась **ровно одна** запись (ноль — скрипт текущей страницы в
       выгрузку не попадает, и вернуть его нечем; больше одной — трогали не
       только её одну);
    2. метки **не было** ни в одной записи до установки — иначе она ничего не
       доказывает;
    3. метка есть в изменившейся записи — значит, изменили её **мы**.

    Нарушение любого из них — `ScriptBridgeUnsafeStateError`: в проекте остался
    пробный скрипт, а какую запись возвращать — неизвестно. Угадывать нельзя:
    ошибка здесь означает запись чужого скрипта в текущую страницу.
    """
    if token_present_in(before, token):
        raise ScriptBridgeUnsafeStateError(
            f"метка {token!r} встречалась в скриптовых записях ещё до установки "
            "пробы: она не доказывает, что запись изменили мы, и опознать цель "
            "нечем. Вероятная причина — в проекте остался пробный скрипт от "
            "предыдущего запуска.")
    if len(before) != len(after):
        raise ScriptBridgeUnsafeStateError(
            f"число скриптовых записей изменилось при установке пробы: "
            f"{len(before)} -> {len(after)}. Сопоставлять записи по номерам "
            "нельзя, цель не установлена.")
    changed = [index for index in range(len(before))
               if before[index] != after[index]]
    if not changed:
        raise ScriptBridgeUnsafeStateError(
            "после установки пробы не изменилась ни одна скриптовая запись: "
            "скрипт текущей страницы в выгрузку не попадает, и вернуть прежний "
            "нечем. Причины может быть две: пробный скрипт остался в проекте "
            "или скрипт этой страницы не сериализуется вовсе — проверьте обе "
            "перед следующим расчётом.")
    if len(changed) > 1:
        raise ScriptBridgeUnsafeStateError(
            f"установка пробы изменила больше одной скриптовой записи: "
            f"{changed}. Инвариант «установка меняет ровно одну запись» нарушен, "
            "и состояние проекта не таково, каким считалось: часть изменений — "
            "не наши. Восстановление по догадке положило бы чужой скрипт в "
            "текущую страницу, поэтому цель не установлена.")
    index = changed[0]
    if token not in after[index]:
        raise ScriptBridgeUnsafeStateError(
            f"изменилась скриптовая запись {index}, но метки в ней нет: значит, "
            "изменилась чужая страница, а не наша. Возврат в неё положил бы "
            "чужой скрипт в текущую страницу; цель не установлена.")
    return index
